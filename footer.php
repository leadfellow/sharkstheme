<script>
// Simple mobile menu toggle
document.addEventListener('DOMContentLoaded', function() {
    const toggle = document.querySelector('.site-nav__toggle');
    const nav = document.querySelector('.site-nav');
    const close = document.querySelector('.site-nav__close');
    
    if (toggle && nav) {
        toggle.addEventListener('click', function() {
            nav.classList.add('is-active');
            toggle.setAttribute('aria-expanded', 'true');
            document.body.style.overflow = 'hidden';
        });
    }
    
    if (close && nav) {
        close.addEventListener('click', function() {
            nav.classList.remove('is-active');
            toggle.setAttribute('aria-expanded', 'false');
            document.body.style.overflow = '';
        });
    }
    
    // Close menu when clicking outside
    if (nav) {
        nav.addEventListener('click', function(e) {
            if (e.target === nav) {
                nav.classList.remove('is-active');
                toggle.setAttribute('aria-expanded', 'false');
                document.body.style.overflow = '';
            }
        });
    }
    
    // Modal functionality
    function openModal(modalId) {
        const modal = document.getElementById(modalId);
        if (modal) {
            modal.style.display = 'block';
            document.body.style.overflow = 'hidden';
            setTimeout(() => modal.classList.add('is-active'), 10);
        }
    }
    
    function closeModal(modal) {
        if (modal) {
            modal.classList.remove('is-active');
            setTimeout(() => {
                modal.style.display = 'none';
                document.body.style.overflow = '';
            }, 300);
        }
    }
    
    // Header CTA Modal
    const ctaButton = document.querySelector('[data-modal="header-cta"]');
    if (ctaButton) {
        ctaButton.addEventListener('click', function(e) {
            e.preventDefault();
            openModal('header-cta-modal');
        });
    }
    
    // Contact Form 7 Modal
    const cf7Button = document.querySelector('[data-modal="header-cf7"]');
    if (cf7Button) {
        cf7Button.addEventListener('click', function(e) {
            e.preventDefault();
            openModal('header-cf7-modal');
        });
    }
    
    // Calendly Modal
    const calendlyButton = document.querySelector('[data-calendly]');
    if (calendlyButton) {
        calendlyButton.addEventListener('click', function(e) {
            e.preventDefault();
            openModal('calendly-modal');
        });
    }
    
    // Close modal buttons
    document.querySelectorAll('.sharks-modal__close, .sharks-modal__overlay').forEach(function(el) {
        el.addEventListener('click', function() {
            const modal = this.closest('.sharks-modal');
            closeModal(modal);
        });
    });
    
    // Close modal on ESC key
    document.addEventListener('keydown', function(e) {
        if (e.key === 'Escape') {
            document.querySelectorAll('.sharks-modal.is-active').forEach(function(modal) {
                closeModal(modal);
            });
        }
    });
    
    // Anchor links smooth scroll - use event delegation for dynamic content
    document.addEventListener('click', function(e) {
        // Find closest anchor tag
        const anchor = e.target.closest('a[href^="#"]');
        if (!anchor) return;
        
        const href = anchor.getAttribute('href');
        
        // Skip if it's just "#" or has special data attributes (modals, etc)
        if (href === '#' || 
            anchor.hasAttribute('data-modal') || 
            anchor.hasAttribute('data-modal-trigger') || 
            anchor.hasAttribute('data-calendly')) {
            return;
        }
        
        // Find target element
        const targetId = href.substring(1);
        const targetElement = document.getElementById(targetId);
        
        if (targetElement) {
            e.preventDefault();
            
            // Close mobile menu if open
            const mobileNav = document.querySelector('.site-nav');
            const toggle = document.querySelector('.site-nav__toggle');
            if (mobileNav && mobileNav.classList.contains('is-active')) {
                mobileNav.classList.remove('is-active');
                if (toggle) toggle.setAttribute('aria-expanded', 'false');
                document.body.style.overflow = '';
            }
            
            // Scroll to target with offset for fixed header
            const header = document.querySelector('.site-header');
            const headerHeight = header ? header.offsetHeight : 80;
            const targetRect = targetElement.getBoundingClientRect();
            const targetPosition = targetRect.top + window.pageYOffset - headerHeight - 20; // Extra 20px spacing
            
            window.scrollTo({
                top: targetPosition,
                behavior: 'smooth'
            });
            
            // Update URL hash without jumping
            if (history.pushState) {
                history.pushState(null, null, href);
            } else {
                window.location.hash = href;
            }
        } else {
            console.warn('Anchor target not found:', targetId);
        }
    });
    
    // Handle anchor links on page load
    if (window.location.hash) {
        setTimeout(function() {
            const targetId = window.location.hash.substring(1);
            const targetElement = document.getElementById(targetId);
            
            if (targetElement) {
                const headerHeight = document.querySelector('.site-header')?.offsetHeight || 80;
                const targetPosition = targetElement.getBoundingClientRect().top + window.pageYOffset - headerHeight;
                
                window.scrollTo({
                    top: targetPosition,
                    behavior: 'smooth'
                });
            }
        }, 100); // Small delay to ensure page is fully loaded
    }
});
